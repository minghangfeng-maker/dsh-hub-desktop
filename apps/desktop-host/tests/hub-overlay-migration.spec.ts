/**
 * The startup migration that takes the Hub's model rows out of the overlay.
 *
 * The cases pin what an upgraded install keeps: every other row, the header with
 * the reserved proxy block, and one extraction file the connector imports as its
 * managed model set. A repeated pass changes nothing, and a document this
 * migration cannot read is reported instead of rewritten.
 */

import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, expect, it } from 'vitest'
import {
  HUB_OVERLAY_FILENAME,
  LEGACY_MODEL_FILE,
  migrateHubOverlayModels,
} from '../src/hub-overlay.ts'

const profiles: string[] = []

afterEach(() => {
  for (const profile of profiles.splice(0)) rmSync(profile, { recursive: true, force: true })
})

/** One profile directory holding the overlay document under test. */
function profileWith(text: string): string {
  const profile = mkdtempSync(join(tmpdir(), 'hub-overlay-migration-'))
  profiles.push(profile)
  writeFileSync(join(profile, HUB_OVERLAY_FILENAME), text, { mode: 0o600 })
  return profile
}

/** The document an installed desktop build wrote: header, proxy block, model rows, a search row. */
const DELIVERED = [
  '# DSH Hub overlay — generated by the hub connector; do not edit.',
  '#',
  '# revision: 7',
  '# Reserved proxy policy, read by the desktop shell before the Host starts:',
  '# hubProxy.noProxy=localhost',
  '- id: hub-connector',
  '  config: {"configSource":"overlay"}',
  '- id: llm-pi-ai',
  '  config: {"providers":{"hub":{"displayName":"DSH Hub","api":"openai-completions","baseURL":"https://hub.example/v1","apiKeyEnv":"HUB_MK_HUB","models":[{"id":"deepseek-v4.1-flash@relay","name":"DeepSeek V4.1 Flash"}]}}}',
  '- id: agent-default-model',
  '  config: {"provider":"hub","model":"deepseek-v4.1-flash@relay"}',
  '- id: web-deepseek-api',
  '  config: {"baseURL":"https://hub.example/v1/tools"}',
  '',
].join('\n')

it('moves both model rows out and keeps every other row and the header', () => {
  const profile = profileWith(DELIVERED)
  const result = migrateHubOverlayModels(profile)
  expect(result.migrated).toBe(true)
  expect(result.removed).toEqual(['llm-pi-ai', 'agent-default-model'])
  const text = readFileSync(join(profile, HUB_OVERLAY_FILENAME), 'utf8')
  expect(text).toContain('# hubProxy.noProxy=localhost')
  expect(text).toContain('- id: hub-connector')
  expect(text).toContain('  config: {"configSource":"overlay"}')
  expect(text).toContain('- id: web-deepseek-api')
  expect(text).toContain('  config: {"baseURL":"https://hub.example/v1/tools"}')
  expect(text).not.toContain('llm-pi-ai')
  expect(text).not.toContain('agent-default-model')
  expect(text.endsWith('\n')).toBe(true)
  // The extraction file is what the connector imports as its managed provider set.
  const legacy = JSON.parse(readFileSync(join(profile, 'desktop-hub', LEGACY_MODEL_FILE), 'utf8')) as {
    providers: Record<string, { baseURL: string }>
    defaultSelection: { provider: string; model: string }
  }
  expect(legacy.providers['hub']?.baseURL).toBe('https://hub.example/v1')
  expect(legacy.defaultSelection).toEqual({ provider: 'hub', model: 'deepseek-v4.1-flash@relay' })
  // The previous file is kept as one backup.
  expect(readdirSync(profile).some(name => name.startsWith(`${HUB_OVERLAY_FILENAME}.bak-`))).toBe(true)
  expect(result.backup).toBeDefined()
})

it('does nothing on a second pass, and nothing to a file without model rows', () => {
  const profile = profileWith(DELIVERED)
  expect(migrateHubOverlayModels(profile).migrated).toBe(true)
  const after = readFileSync(join(profile, HUB_OVERLAY_FILENAME), 'utf8')
  const backups = readdirSync(profile).filter(name => name.startsWith(`${HUB_OVERLAY_FILENAME}.bak-`)).length
  expect(migrateHubOverlayModels(profile)).toEqual({ migrated: false, removed: [] })
  expect(readFileSync(join(profile, HUB_OVERLAY_FILENAME), 'utf8')).toBe(after)
  expect(readdirSync(profile).filter(name => name.startsWith(`${HUB_OVERLAY_FILENAME}.bak-`))).toHaveLength(backups)
})

it('leaves a document it cannot parse in place and reports why', () => {
  // A hand-written overlay using block-style config: the migration refuses rather
  // than dropping a section it does not understand.
  const profile = profileWith([
    '# DSH Hub overlay — generated by the hub connector; do not edit.',
    '- id: llm-pi-ai',
    '  config:',
    '    providers:',
    '      hub:',
    '        api: openai-completions',
    '',
  ].join('\n'))
  const before = readFileSync(join(profile, HUB_OVERLAY_FILENAME), 'utf8')
  const result = migrateHubOverlayModels(profile)
  expect(result.migrated).toBe(false)
  expect(result.error).toMatch(/cannot parse/u)
  expect(readFileSync(join(profile, HUB_OVERLAY_FILENAME), 'utf8')).toBe(before)
  expect(() => readFileSync(join(profile, 'desktop-hub', LEGACY_MODEL_FILE))).toThrow()
})

it('leaves the original overlay in place when the replacement document cannot be written', () => {
  const profile = profileWith(DELIVERED)
  // The migration prepares `<overlay>.migrating`; a directory there makes that write fail.
  mkdirSync(join(profile, `${HUB_OVERLAY_FILENAME}.migrating`))
  const before = readFileSync(join(profile, HUB_OVERLAY_FILENAME), 'utf8')
  const failed = migrateHubOverlayModels(profile)
  expect(failed.migrated).toBe(false)
  expect(failed.error).toBeTruthy()
  // Byte-for-byte identical: the account/search/proxy rows still load next start.
  expect(readFileSync(join(profile, HUB_OVERLAY_FILENAME), 'utf8')).toBe(before)
  expect(readdirSync(profile).some(name => name.startsWith(`${HUB_OVERLAY_FILENAME}.bak-`))).toBe(false)
  // Retrying once the obstacle is gone succeeds.
  rmSync(join(profile, `${HUB_OVERLAY_FILENAME}.migrating`), { recursive: true, force: true })
  expect(migrateHubOverlayModels(profile).migrated).toBe(true)
})

it('leaves the original overlay in place when the final atomic replacement fails', () => {
  const profile = profileWith(DELIVERED)
  const before = readFileSync(join(profile, HUB_OVERLAY_FILENAME), 'utf8')
  const failed = migrateHubOverlayModels(profile, {
    replace: () => { throw new Error('injected replacement failure') },
  })
  expect(failed.migrated).toBe(false)
  expect(failed.error).toMatch(/injected replacement failure/u)
  expect(readFileSync(join(profile, HUB_OVERLAY_FILENAME), 'utf8')).toBe(before)
  // No half-written document and no orphan of this pass remain beside it.
  expect(readdirSync(profile).filter(name => name.startsWith(`${HUB_OVERLAY_FILENAME}.`))).toEqual([])
  // The normal next start retries and completes.
  expect(migrateHubOverlayModels(profile).migrated).toBe(true)
  expect(readFileSync(join(profile, HUB_OVERLAY_FILENAME), 'utf8')).not.toContain('llm-pi-ai')
})

it('reports success even when trimming old backups fails, and keeps this pass backup', () => {
  const profile = profileWith(DELIVERED)
  // One old backup path is a directory, so removing it without `recursive` throws.
  mkdirSync(join(profile, `${HUB_OVERLAY_FILENAME}.bak-9999999999999`))
  const result = migrateHubOverlayModels(profile)
  expect(result.migrated).toBe(true)
  expect(result.error).toBeUndefined()
  expect(result.backup).toBeDefined()
  expect(existsSync(result.backup ?? '')).toBe(true)
  // The overlay itself is the migrated document, not the original.
  expect(readFileSync(join(profile, HUB_OVERLAY_FILENAME), 'utf8')).not.toContain('llm-pi-ai')
})

it('keeps the old extraction file when a stale overlay reappears', () => {
  const profile = profileWith(DELIVERED)
  expect(migrateHubOverlayModels(profile).migrated).toBe(true)
  // A second installation step re-seeds the overlay from an old manifest.
  writeFileSync(join(profile, HUB_OVERLAY_FILENAME), DELIVERED, { mode: 0o600 })
  const older = readFileSync(join(profile, 'desktop-hub', LEGACY_MODEL_FILE), 'utf8')
  expect(migrateHubOverlayModels(profile).migrated).toBe(true)
  // The connector's own state wins over a migrated copy, so the file is not overwritten.
  expect(readFileSync(join(profile, 'desktop-hub', LEGACY_MODEL_FILE), 'utf8')).toBe(older)
})

it('creates nothing when the profile has no overlay', () => {
  const profile = mkdtempSync(join(tmpdir(), 'hub-overlay-absent-'))
  profiles.push(profile)
  expect(migrateHubOverlayModels(profile)).toEqual({ migrated: false, removed: [] })
  expect(readdirSync(profile)).toEqual([])
  mkdirSync(join(profile, 'desktop-hub'))
})
